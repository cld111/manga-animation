"""Phase 9 real-world evaluation run: the full production pipeline (page-level AND panel-aware

analysis) over the Real-World Evaluation Dataset (`configs/phase9_realworld_eval_dataset.yaml`,
10 real pages, 8 series never used by any earlier phase), plus a repeated-run VLM nondeterminism
check on those same new samples. Optionally also includes the existing 7-sample Phase 8 golden
regression set (`--include-golden`) so every number in one report comes from one real,
single-session run against the exact commit under test, rather than stitching together two
different sessions' JSON artifacts.

**Run this on the remote Kaggle/Jupyter GPU worker, never locally** -- see ADR 0003 and
CLAUDE.md's standing policy. Reuses `manga_animation.evaluation.harness` (extracted from
`scripts/run_phase3_3_evaluation.py` for exactly this reuse, Phase 9) for the actual per-sample
`run_pipeline` invocation -- this script's own job is orchestrating the dataset/resume/
persistence/reporting concerns specific to the larger, characterization-focused Phase 9 dataset.

No page gets an automatic, fabricated fallback plan -- every result here is from fully
automatic operation, same policy as `run_phase3_3_evaluation.py`.

**Resumable** (Phase 9 brief section 17: "If a run is interrupted, the evaluator should be able
to resume from completed samples"): every sample's outcome is written to the output JSON
immediately after it completes, not only at the end. Pass `--resume <path>` with a
previously-written output file to skip every (sample_id, mode) pair (and nondeterminism
sample_id) already present in it and continue from there -- a killed/interrupted run never
has to re-pay for already-completed real GPU inference.

Usage (on the GPU worker, after `git pull`):
    uv run python scripts/run_phase9_evaluation.py
    uv run python scripts/run_phase9_evaluation.py --include-golden
    uv run python scripts/run_phase9_evaluation.py \\
        --resume outputs/experiments/phase9_evaluation_<ts>.json
    uv run python scripts/run_phase9_evaluation.py --nondeterminism-runs 2

Writes `outputs/experiments/phase9_evaluation_<timestamp>.json` (per-page, per-mode outcomes;
both modes' `EvaluationReport`s; nondeterminism summaries; dataset composition) and, for every
page/mode that reaches rendering, the actual video under
`outputs/videos/phase9/<mode>/<page-stem>/` (git-ignored generated artifacts, per ADR 0002 --
never committed).
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Literal

from manga_animation.core.config import load_config
from manga_animation.core.logging import setup_logging
from manga_animation.evaluation import (
    EvalSample,
    EvaluationReport,
    PageRunOutcome,
    classify_outcome,
    compute_metrics,
    dataset_composition,
    load_eval_dataset,
)
from manga_animation.evaluation.dataset import REALWORLD_DATASET_PATH
from manga_animation.evaluation.harness import (
    environment_metadata,
    panel_detection_evidence,
    run_nondeterminism_check,
    run_one_sample,
)
from manga_animation.pipeline.orchestrator import build_default_clients

_MODES: tuple[Literal["page", "panel"], ...] = ("page", "panel")


def _load_dataset(include_golden: bool) -> list[EvalSample]:
    realworld = load_eval_dataset(REALWORLD_DATASET_PATH)
    if not include_golden:
        return realworld
    golden = load_eval_dataset()
    return golden + realworld


def _check_missing_images(samples: list[EvalSample]) -> None:
    missing = [s for s in samples if not Path(s.image_path).exists()]
    if not missing:
        return
    fetchable = [s.image_path for s in missing if s.fetch_script]
    unfetchable = [s.image_path for s in missing if not s.fetch_script]
    detail = []
    if fetchable:
        detail.append(f"fetch first: {fetchable} (see fetch_script per sample)")
    if unfetchable:
        detail.append(
            f"no fetch script exists for: {unfetchable} -- obtain these directly from the "
            "project owner, they cannot be regenerated by any script"
        )
    raise SystemExit("missing evaluation sample image(s) -- " + "; ".join(detail))


def _load_resume_state(resume_path: Path | None) -> dict[str, Any]:
    """Loads a previous partial run's raw JSON, or an empty skeleton if `--resume` was not

    given or the path doesn't exist yet (a fresh run that will be written to that path for the
    first time). Only the raw `outcomes`/`nondeterminism` sections are consulted -- reports are
    always recomputed fresh at the end from the full (resumed + new) outcome set, never resumed
    themselves, so a report is never stale relative to the outcomes it summarizes.
    """
    if resume_path is None or not resume_path.exists():
        return {"outcomes": {mode: [] for mode in _MODES}, "nondeterminism": []}
    data = json.loads(resume_path.read_text())
    data.setdefault("outcomes", {mode: [] for mode in _MODES})
    for mode in _MODES:
        data["outcomes"].setdefault(mode, [])
    data.setdefault("nondeterminism", [])
    return data


def _write_json(path: Path, summary: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(summary, indent=2, default=str))


def _render_rates_in_place(
    reports: dict[str, EvaluationReport], serialized_reports: dict[str, dict[str, Any]]
) -> None:
    """Identical in spirit to `run_phase3_3_evaluation.py`'s own helper of the same name (kept

    script-local rather than shared, since it is a thin, five-line JSON-display convenience, not
    real per-sample runner logic) -- adds a human-readable "rendered" string to every
    `Rate`-shaped dict.
    """
    for mode, mode_report in serialized_reports.items():
        for key, value in list(mode_report.items()):
            if isinstance(value, dict) and "numerator" in value and "denominator" in value:
                mode_report[key] = {**value, "rendered": str(reports[mode].__getattribute__(key))}


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--env", default="kaggle", help="config profile (see configs/)")
    parser.add_argument("--out-dir", type=Path, default=Path("outputs/videos/phase9"))
    parser.add_argument("--experiments-dir", type=Path, default=Path("outputs/experiments"))
    parser.add_argument(
        "--include-golden",
        action="store_true",
        help="also run the existing 7-sample Phase 8 golden regression set in this same "
        "session, for one internally-consistent combined report instead of stitching together "
        "two different sessions' JSON artifacts.",
    )
    parser.add_argument(
        "--resume",
        type=Path,
        default=None,
        help="path to a previous (possibly partial) phase9_evaluation_*.json to continue from "
        "-- every (sample_id, mode) pair and nondeterminism sample_id already present there is "
        "skipped, not re-run.",
    )
    parser.add_argument(
        "--nondeterminism-runs",
        type=int,
        default=2,
        help="repeated analyze_page() calls per nondeterminism sample (default lower than "
        "run_phase3_3_evaluation.py's 3, for cost control on the larger Phase 9 dataset -- see "
        "brief section 17's resource-efficiency requirement)",
    )
    parser.add_argument(
        "--nondeterminism-samples",
        nargs="*",
        default=None,
        help="sample_ids to repeat-run for the nondeterminism check. Defaults to only the NEW "
        "Real-World Evaluation Dataset sample_ids (not the golden set, even with "
        "--include-golden -- its nondeterminism is already characterized, Phase 3.3/7.2.2/"
        "Phase 8), to keep the primary Phase 9 measurement focused and cheap.",
    )
    args = parser.parse_args()

    samples = _load_dataset(args.include_golden)
    realworld_sample_ids = [s.sample_id for s in load_eval_dataset(REALWORLD_DATASET_PATH)]
    if args.nondeterminism_samples is None:
        args.nondeterminism_samples = realworld_sample_ids

    _check_missing_images(samples)

    setup_logging(debug=False)
    config = load_config(args.env)
    device = config.resolve_device()
    clients = build_default_clients(config)
    vlm_client = clients[0]

    panel_evidence = {s.sample_id: panel_detection_evidence(Path(s.image_path)) for s in samples}
    samples_by_id = {s.sample_id: s for s in samples}

    state = _load_resume_state(args.resume)
    out_path = args.resume if args.resume is not None else None
    if out_path is None:
        args.experiments_dir.mkdir(parents=True, exist_ok=True)
        timestamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
        out_path = args.experiments_dir / f"phase9_evaluation_{timestamp}.json"
    print(f"writing incremental progress to {out_path}")

    already_done: dict[str, set[str]] = {
        mode: {o["sample_id"] for o in state["outcomes"][mode]} for mode in _MODES
    }

    def _persist() -> None:
        summary = {
            "environment": environment_metadata(device),
            "config_env": args.env,
            "model_variants": config.model_variants,
            "include_golden": args.include_golden,
            "dataset_composition": dataset_composition(load_eval_dataset(REALWORLD_DATASET_PATH)),
            "outcomes": state["outcomes"],
            "nondeterminism": state["nondeterminism"],
        }
        _write_json(out_path, summary)

    for mode in _MODES:
        for sample in samples:
            if sample.sample_id in already_done[mode]:
                print(f"[{mode}] {sample.sample_id}: SKIPPED (already in {out_path})")
                continue
            panel_count, panel_sources = panel_evidence[sample.sample_id]
            outcome = run_one_sample(
                sample,
                mode,
                config,
                clients,
                args.out_dir / mode / Path(sample.image_path).stem,
                panel_count,
                panel_sources,
            )
            state["outcomes"][mode].append(json.loads(outcome.model_dump_json()))
            already_done[mode].add(sample.sample_id)
            _persist()
            status = classify_outcome(outcome, samples_by_id.get(sample.sample_id))
            seam = None
            if outcome.render_summary is not None:
                seam = outcome.render_summary.seam_artifact_suspected
            print(
                f"[{mode}] {sample.sample_id}: {status} -- {outcome.status} "
                f"({outcome.failing_stage or 'ok'}) seam_artifact_suspected={seam}"
            )

    outcomes: dict[str, list[PageRunOutcome]] = {
        mode: [PageRunOutcome.model_validate(o) for o in state["outcomes"][mode]] for mode in _MODES
    }
    reports: dict[str, EvaluationReport] = {
        mode: compute_metrics(outcomes[mode], samples_by_id) for mode in _MODES
    }

    nondeterminism_done = {s["sample_id"] for s in state["nondeterminism"]}
    for sid in args.nondeterminism_samples:
        if sid in nondeterminism_done:
            print(f"[nondeterminism] {sid}: SKIPPED (already in {out_path})")
            continue
        if sid not in samples_by_id:
            print(f"[nondeterminism] {sid}: SKIPPED (not in the loaded dataset)")
            continue
        summary = run_nondeterminism_check(
            samples_by_id[sid], config, vlm_client, args.nondeterminism_runs
        )
        state["nondeterminism"].append(asdict(summary))
        _persist()
        print(
            f"[nondeterminism] {sid}: outcome_stable={summary.outcome_stable} "
            f"target_category_stable={summary.target_category_stable}"
        )

    serialized_reports = {mode: asdict(reports[mode]) for mode in reports}
    _render_rates_in_place(reports, serialized_reports)
    final_summary = {
        "environment": environment_metadata(device),
        "config_env": args.env,
        "model_variants": config.model_variants,
        "include_golden": args.include_golden,
        "dataset_composition": dataset_composition(load_eval_dataset(REALWORLD_DATASET_PATH)),
        "outcomes": state["outcomes"],
        "reports": serialized_reports,
        "nondeterminism": state["nondeterminism"],
    }
    _write_json(out_path, final_summary)

    print("\nPHASE 9 EVALUATION RUN COMPLETE")
    for mode in _MODES:
        print(f"\n--- {mode}-level report ---")
        r = reports[mode]
        print(f"  sample_count: {r.sample_count}")
        print(f"  usable_target_rate: {r.usable_target_rate}")
        print(f"  static_rate: {r.static_rate}")
        print(f"  grounding_success_rate: {r.grounding_success_rate}")
        print(f"  validation_acceptance_rate: {r.validation_acceptance_rate}")
        print(f"  end_to_end_completion_rate: {r.end_to_end_completion_rate}")
        print(f"  semantic_false_positive_rate: {r.semantic_false_positive_rate}")
        print(f"  semantic_false_negative_rate: {r.semantic_false_negative_rate}")
        print(f"  unresolved_ground_truth_count: {r.unresolved_ground_truth_count}")
        if r.panel_detection_multi_panel_rate is not None:
            print(f"  panel_detection_multi_panel_rate: {r.panel_detection_multi_panel_rate}")
        print(f"  secondary_object_render_rate: {r.secondary_object_render_rate}")
        print(f"  micro_object_render_rate: {r.micro_object_render_rate}")
        sb = r.status_breakdown
        print(
            "  status_breakdown: "
            f"PASS={sb.pass_count} PASS_WITH_FALLBACK={sb.pass_with_fallback_count} "
            f"REJECTED={sb.rejected_count} ERROR={sb.error_count} (total={sb.total})"
        )
    print("\n--- nondeterminism ---")
    for s in state["nondeterminism"]:
        print(
            f"  {s['sample_id']}: outcome_stable={s['outcome_stable']} "
            f"target_category_stable={s['target_category_stable']}"
        )
    print(f"\nwrote {out_path}")


if __name__ == "__main__":
    main()
